"""Opt-in niri adapter. Only Glyph's managed binding file is edited at runtime."""
import json
import os
import re
import select
import shutil
import subprocess
import sys
import uuid
from pathlib import Path

from paths import APP_ID, APP_ROOT, CONFIG_DIR


def idle_config():
    return f'// Glyph shortcuts are inactive.\nwindow-rule {{\n    match app-id={kdl_string(APP_ID)}\n    open-floating true\n}}\nbinds {{}}\n'


def kdl_string(value):
    return json.dumps(str(value), ensure_ascii=False)


def valid_keys(keys):
    return len(set(keys)) == 3 and all(
        re.fullmatch(r"(?:(?:Ctrl|Alt|Shift|Mod|Super)\+)+[A-Za-z0-9_-]+", key)
        and any(part in key.split("+")[:-1] for part in ("Ctrl", "Alt", "Mod", "Super"))
        for key in keys
    )


def bindings_text(keys, launcher=None):
    if not valid_keys(keys):
        raise ValueError("快捷键需包含 Ctrl、Alt 或 Super，且三个快捷键不能重复")
    # AppImage mount paths are temporary; the compositor must invoke the image.
    launcher = launcher or os.environ.get("GLYPH_LAUNCHER") or APP_ROOT / "bin" / "glyph"
    lines = [idle_config().removesuffix("binds {}\n"), "// Generated by Glyph while it is running.", "binds {"]
    for key, action in zip(keys, ("capture", "ocr", "toggle")):
        lines.append(f"    {key} repeat=false {{ spawn {kdl_string(launcher)} \"--action\" \"{action}\"; }}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


class Hotkeys:
    def __init__(self):
        self.config = CONFIG_DIR / "hotkeys.json"
        self.bindings = CONFIG_DIR / "niri-bindings.kdl"
        self.active = False
        self.error = ""
        self.token = f"// Glyph session {uuid.uuid4().hex}"
        self.guard_pipe = None
        self.guard = None

    def configure(self, *keys):
        if not valid_keys(keys):
            self.error = "三个快捷键必须不同，并包含 Ctrl、Alt 或 Super。"
            return False
        if not self.config.exists():
            self.error = "全局快捷键偏好已保存；请先在安装时启用 niri 集成。"
            return True
        try:
            config = json.loads(self.config.read_text())
            if config.get("backend") != "niri" or not shutil.which("niri"):
                raise ValueError("当前桌面没有可用的 niri 快捷键集成")
            root_config = Path(config["config"])
            if not root_config.exists() or kdl_string(self.bindings) not in root_config.read_text():
                raise ValueError("niri 主配置没有启用 Glyph 的独立绑定文件")
            previous = self.bindings.read_text() if self.bindings.exists() else idle_config()
            # In an AppImage the mount may disappear immediately after a crash.
            # Wait until the guardian has loaded its interpreter/modules before
            # publishing any active binding, not merely until Popen succeeds.
            self.ensure_guard_ready()
            atomic_write(self.bindings, self.token + "\n" + bindings_text(keys))
            check = subprocess.run(["niri", "validate", "--config", str(root_config)], capture_output=True, text=True, timeout=5)
            if check.returncode:
                atomic_write(self.bindings, previous)
                raise ValueError("快捷键冲突或 niri 配置校验失败，原绑定已保留")
            self.active = True
            self.error = "niri 全局快捷键已启用；彻底退出 Glyph 时释放。"
            return True
        except (OSError, ValueError, KeyError, RuntimeError, subprocess.TimeoutExpired) as error:
            self.error = str(error)
            return False

    def ensure_guard_ready(self):
        if self.guard_pipe is not None: return
        read_fd, write_fd = os.pipe()
        ready_read, ready_write = os.pipe()
        try:
            self.guard = subprocess.Popen(
                [sys.executable, str(Path(__file__).resolve()), "--guard", str(self.bindings), self.token, "--ready-fd", str(ready_write)],
                stdin=read_fd, pass_fds=(ready_write,), stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL, start_new_session=True)
            os.close(ready_write); ready_write = None
            if not select.select([ready_read], [], [], 5)[0] or os.read(ready_read, 1) != b"R":
                raise RuntimeError("快捷键保护进程未就绪，未启用全局键位")
            self.guard_pipe = write_fd; write_fd = None
        finally:
            for descriptor in (read_fd, write_fd, ready_read, ready_write):
                if descriptor is not None: os.close(descriptor)

    def close(self):
        if self.active:
            if self.bindings.exists() and self.token in self.bindings.read_text():
                atomic_write(self.bindings, idle_config())
            self.active = False
        if self.guard_pipe is not None:
            os.close(self.guard_pipe); self.guard_pipe = None
        if self.guard:
            try: self.guard.wait(timeout=2)
            except subprocess.TimeoutExpired: self.guard.terminate()
            self.guard = None


if __name__ == "__main__" and len(sys.argv) in (4, 6) and sys.argv[1] == "--guard":
    # Blocking pipe: no polling, and EOF also arrives after an application crash.
    if len(sys.argv) == 6 and sys.argv[4] == "--ready-fd":
        ready_fd = int(sys.argv[5]); os.write(ready_fd, b"R"); os.close(ready_fd)
    sys.stdin.buffer.read()
    target = Path(sys.argv[2]); token = sys.argv[3]
    try:
        if target.exists() and token in target.read_text():
            atomic_write(target, idle_config())
    except OSError:
        pass
